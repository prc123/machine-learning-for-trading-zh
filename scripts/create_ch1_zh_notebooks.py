def translate_notebook(source: Path, translations: dict[int, str]) -> Path:
    with source.open(encoding="utf-8") as handle:
        notebook = json.load(handle)

    markdown_indices = [
        index for index, cell in enumerate(notebook["cells"]) if cell["cell_type"] == "markdown"
    ]
    if set(translations) != set(markdown_indices):
        missing = sorted(set(markdown_indices) - set(translations))
        extra = sorted(set(translations) - set(markdown_indices))
        raise ValueError(f"{source}: missing={missing}, extra={extra}")

    for index, text in translations.items():
        notebook["cells"][index]["source"] = text.splitlines(keepends=True)

    output = source.with_name(source.stem + ".zh-CN.ipynb")
    with output.open("w", encoding="utf-8", newline="\n") as handle:
        json.dump(notebook, handle, ensure_ascii=False, indent=1)
        handle.write("\n")
    return output


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    chapter = root / "01_process_is_edge"
    for filename, translations in (
        ("factor_regimes.ipynb", FACTOR_REGIMES),
        ("macro_regimes.ipynb", MACRO_REGIMES),
    ):
        output = translate_notebook(chapter / filename, translations)
        print(f"Wrote {output.relative_to(root)}")


if __name__ == "__main__":
    main()
